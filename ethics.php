				<article class="flex-1 min-w-0 bg-white rounded-xl shadow-sm border border-gray-100 p-6 md:p-8 lg:p-10 ethics-content space-y-10 text-[15px] leading-7 text-gray-700">

					<div class="bg-[#f8f5fc] border-l-4 border-[#80078b] rounded-r-lg p-5">
						<p class="m-0 text-gray-700"><strong class="text-[#250242]">Publication Ethics and Publication Malpractice Statement</strong> — Last updated: <strong>2 September 2026</strong>. This Statement informs authors, editors, reviewers and readers how ASFIRJ safeguards the scholarly record. Our policies are informed by internationally recognised best practices, including the principles and guidance of the <em>Committee on Publication Ethics (COPE)</em>.</p>
					</div>

					<section id="commitment" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Our commitment to publication ethics</h2>
						<p>ASFIRJ is committed to maintaining the highest standards of integrity, transparency, accountability, and ethical conduct in scholarly publishing. Manuscripts are considered solely on the basis of their scientific merit, originality, methodological rigor, relevance, and quality, without discrimination based on nationality, ethnicity, gender, institutional affiliation, seniority, or other non-scientific characteristics.</p>
						<p>ASFIRJ recognizes that maintaining the integrity of the scholarly record is a shared responsibility involving authors, editors, peer reviewers, the publisher, institutions, and other stakeholders. The journal therefore expects all parties involved in the publication process to adhere to high standards of professional and ethical conduct.</p>
						<p>ASFIRJ is committed to maintaining the integrity of the scholarly record and to investigating suspected publication or research misconduct fairly and transparently. The journal's publication ethics policies are informed by internationally recognized best practices, including the principles and guidance of the Committee on Publication Ethics (COPE).</p>
					</section>

					<section id="publisher" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Responsibilities of the Publisher</h2>
						<p>The publisher (the African Science Frontiers Initiatives – ASFI) of ASFIRJ is committed to:</p>
						<ul>
							<li>supporting the integrity and independence of the journal's editorial decision-making</li>
							<li>maintaining the integrity of the scholarly record</li>
							<li>providing appropriate procedures for addressing suspected publication misconduct</li>
							<li>supporting editors in handling ethical concerns and complaints</li>
							<li>ensuring that published articles remain accessible as part of the scholarly record</li>
							<li>issuing corrections, retractions, expressions of concern, or other notices when necessary to maintain the accuracy and integrity of the published record</li>
							<li>ensuring that commercial, financial, or other external interests do not improperly influence editorial decisions</li>
						</ul>
						<p>ASFI will cooperate, where appropriate, with authors' institutions, funders, other journals, indexing services, and relevant research or regulatory bodies when serious concerns about research or publication integrity arise.</p>
					</section>

					<section id="editor" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Responsibilities of the Editor-in-Chief and Editorial Team</h2>
						<p>The Editor-in-Chief and editorial team are responsible for maintaining the academic and ethical standards of ASFIRJ. Editorial decisions shall be based primarily on the scientific quality, originality, methodological rigor, significance, and relevance of submitted work.</p>
						<p>Editors shall:</p>
						<ul>
							<li>evaluate manuscripts fairly and objectively</li>
							<li>ensure that manuscripts undergo appropriate peer review</li>
							<li>select suitably qualified and independent reviewers</li>
							<li>protect the confidentiality of submitted manuscripts and associated editorial communications</li>
							<li>identify and manage potential conflicts of interest</li>
							<li>avoid discrimination or bias in editorial decision-making</li>
							<li>ensure that editorial decisions are not influenced by commercial or personal interests</li>
							<li>investigate credible allegations of publication or research misconduct</li>
							<li>take appropriate action when ethical concerns are identified</li>
							<li>maintain the integrity of the published record</li>
							<li>ensure that corrections or retractions are issued when warranted</li>
						</ul>
						<p>Editors shall not use unpublished information contained in submitted manuscripts for their own research or personal advantage without the author's explicit permission. Editors who have a conflict of interest with a submitted manuscript—including manuscripts authored by themselves, close collaborators, family members, or individuals with whom they have a significant professional or personal relationship—shall not participate in the editorial decision-making process for that manuscript. An alternative editor shall be assigned where appropriate. ASFIRJ also expects editors to avoid practices intended to artificially increase journal metrics, including inappropriate or coercive citation practices.</p>
					</section>

					<section id="authors" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Responsibilities of Authors</h2>
						<p>Authors submitting manuscripts to ASFIRJ are expected to:</p>
						<ul>
							<li>ensure that the work submitted is original and has been conducted and reported ethically</li>
							<li>provide an accurate and complete account of the research</li>
							<li>ensure that the data and results are reported honestly</li>
							<li>appropriately acknowledge and cite the work of others</li>
							<li>ensure that all individuals who meet authorship criteria are appropriately included as authors</li>
							<li>ensure that individuals who do not meet authorship criteria are not listed as authors</li>
							<li>disclose relevant conflicts of interest</li>
							<li>disclose sources of funding and other relevant support</li>
							<li>obtain appropriate ethical approval and informed consent where required</li>
							<li>comply with applicable laws, regulations, institutional requirements, and disciplinary ethical standards</li>
							<li>ensure that the manuscript has not been published previously, except where appropriately declared and permitted</li>
							<li>not submit the same manuscript simultaneously to more than one journal</li>
							<li>cooperate with the journal in addressing questions concerning the integrity of their work</li>
							<li>promptly notify ASFIRJ if a significant error or inaccuracy is identified in a submitted or published article</li>
						</ul>
						<p>Authors are responsible for the accuracy and integrity of the work they submit and publish.</p>
					</section>

					<section id="authorship" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Authorship and contributorship</h2>
						<p>ASFIRJ considers authorship to be an important matter of research integrity. Individuals listed as authors should have made a substantial intellectual or scholarly contribution to the work and should have participated sufficiently in the research to take responsibility for the appropriate aspects of the work.</p>
						<p>All listed authors should:</p>
						<ul>
							<li>have made a meaningful contribution to the work</li>
							<li>have participated in drafting the manuscript or critically revising it</li>
							<li>have approved the final version of the manuscript</li>
							<li>agree to be accountable for the integrity of the work</li>
						</ul>
						<p>Individuals who contributed to the work but do not meet the criteria for authorship should be appropriately acknowledged.</p>
						<p>ASFIRJ does not permit:</p>
						<ul>
							<li>guest or honorary authorship</li>
							<li>ghost authorship</li>
							<li>fabrication or misrepresentation of authorship</li>
							<li>inappropriate addition or removal of authors during the publication process</li>
							<li>manipulation of author order for unethical purposes</li>
						</ul>
						<p>Any substantial change to authorship after submission must be justified and approved by all authors and accepted by the journal before publication.</p>
					</section>

					<section id="originality" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Originality, plagiarism and duplicate publication</h2>
						<p>ASFIRJ considers plagiarism, fabrication, falsification, duplicate publication, and other forms of inappropriate appropriation or manipulation of scholarly work to be serious breaches of publication ethics.</p>
						<p>Manuscripts submitted to ASFIRJ must be original and must not:</p>
						<ul>
							<li>contain plagiarized material</li>
							<li>reproduce substantial portions of another person's work without appropriate attribution</li>
							<li>contain fabricated or falsified data</li>
							<li>substantially duplicate previously published work without appropriate justification and disclosure</li>
							<li>be simultaneously submitted to another journal</li>
							<li>improperly reuse previously published material without appropriate citation and permission where required</li>
						</ul>
						<p>ASFIRJ may use plagiarism or similarity-detection tools and may conduct additional investigations where substantial overlap or other concerns are identified. Where misconduct is suspected, the journal may request explanations, supporting documentation, original data, ethical approval documentation, or other relevant information from the authors.</p>
					</section>

					<section id="fabrication" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Fabrication, falsification and research misconduct</h2>
						<p>ASFIRJ does not tolerate:</p>
						<ul>
							<li>fabrication of data, results, participants, images, or other research materials</li>
							<li>falsification or inappropriate manipulation of research data, methods, images, or results</li>
							<li>manipulation of the publication or peer-review process</li>
							<li>plagiarism</li>
							<li>inappropriate authorship practices</li>
							<li>duplicate or redundant publication</li>
							<li>citation manipulation</li>
							<li>fraudulent peer-review practices</li>
							<li>deliberate misrepresentation of research findings</li>
							<li>other forms of research or publication misconduct</li>
						</ul>
						<p>Where credible concerns arise, ASFIRJ will investigate them in a fair and proportionate manner. Where appropriate, the journal may seek assistance from the authors' institution, employer, funder, ethics committee, or other relevant authority.</p>
					</section>

					<section id="peer-review-ethics" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Peer-review ethics</h2>
						<p>Peer review is an essential component of ASFIRJ's editorial process.</p>
						<p>Reviewers are expected to:</p>
						<ul>
							<li>evaluate manuscripts objectively and constructively</li>
							<li>have appropriate expertise for the manuscript under review</li>
							<li>maintain confidentiality</li>
							<li>declare any potential conflict of interest</li>
							<li>complete reviews within the agreed timeframe or inform the editor if this is not possible</li>
							<li>identify potential ethical concerns</li>
							<li>identify substantial similarity or suspected plagiarism where apparent</li>
							<li>avoid using information obtained through peer review for personal or professional advantage</li>
							<li>avoid personal, discriminatory, hostile, or otherwise inappropriate comments</li>
						</ul>
						<p>Reviewers should not recommend citations to their own work or the work of associates unless there is a genuine scholarly justification. Reviewers who have a conflict of interest or believe that they cannot provide an impartial assessment should decline the invitation and notify the editor.</p>
					</section>

					<section id="conflicts" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Conflicts of interest</h2>
						<p>ASFIRJ requires authors, editors, reviewers, and other relevant contributors to disclose financial and non-financial conflicts of interest that could influence, or reasonably be perceived to influence, their judgment.</p>
						<p>Potential conflicts may include:</p>
						<ul>
							<li>financial interests</li>
							<li>employment or consultancy relationships</li>
							<li>research funding</li>
							<li>patents or intellectual property</li>
							<li>personal relationships</li>
							<li>professional or institutional relationships</li>
							<li>close collaboration with authors</li>
							<li>academic competition</li>
							<li>other interests that could reasonably affect impartiality</li>
						</ul>
						<p>The existence of a conflict of interest does not necessarily prevent publication or participation in peer review. However, conflicts must be appropriately disclosed and managed. Where necessary, an editor or reviewer may be recused from a manuscript.</p>
					</section>

					<section id="ethical-approval" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Ethical approval and research involving humans or animals</h2>
						<p>Authors conducting research involving human participants, human data, identifiable biological material, or animals must comply with applicable ethical and regulatory requirements. Where required, authors must obtain approval from an appropriate research ethics committee/institutional review board or equivalent body before commencing the research.</p>
						<p>Manuscripts should provide appropriate information regarding:</p>
						<ul>
							<li>ethical approval</li>
							<li>informed consent</li>
							<li>participant confidentiality</li>
							<li>data protection</li>
							<li>animal welfare, where applicable</li>
						</ul>
						<p>Authors should not disclose personally identifiable information without appropriate consent and justification. ASFIRJ reserves the right to request evidence of ethical approval where appropriate.</p>
					</section>

					<section id="informed-consent" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Informed consent and patient/participant privacy</h2>
						<p>Where manuscripts contain information that could identify individual participants, authors must ensure that appropriate informed consent for publication has been obtained where required. Authors should remove unnecessary identifying information and take appropriate measures to protect participant confidentiality. Where consent is required, authors should be able to provide evidence of consent to the journal upon request.</p>
					</section>

					<section id="data-integrity" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Data integrity, transparency and reproducibility</h2>
						<p>ASFIRJ encourages authors to report research transparently and provide sufficient methodological detail to enable appropriate evaluation and, where feasible, replication. Authors should retain relevant research data and documentation for a reasonable period and should be prepared to provide supporting information to the editors where legitimate questions arise regarding the integrity of the research. Where appropriate and ethically permissible, ASFIRJ encourages the sharing of research data, analytical code, protocols, and other supporting materials. Data sharing must comply with applicable ethical, legal, privacy, confidentiality, and institutional requirements.</p>
					</section>

					<section id="ai" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Use of artificial intelligence and AI-assisted technologies</h2>
						<p>ASFIRJ recognizes that artificial intelligence (AI), including generative AI tools, may be used in certain aspects of research and manuscript preparation. Authors remain fully responsible for the accuracy, originality, integrity, and ethical content of their manuscripts, regardless of whether AI-assisted technologies were used. AI tools must not be listed as authors. Authors should disclose the use of generative AI or AI-assisted technologies in manuscript preparation where such use is relevant to the content or development of the manuscript, in accordance with ASFIRJ's current AI policy. AI tools must not be used to fabricate or falsify data, references, images, results, or other scholarly content. Reviewers and editors must not upload confidential manuscripts or unpublished material into AI systems as doing so may compromise confidentiality or intellectual property. ASFIRJ may update its AI policy as technologies and international publishing standards evolve.</p>
					</section>

					<section id="citation" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Citation ethics</h2>
						<p>ASFIRJ expects citations to be relevant, accurate, and appropriate.</p>
						<p>Authors, reviewers, and editors must not engage in:</p>
						<ul>
							<li>coercive citation</li>
							<li>excessive self-citation</li>
							<li>citation stacking</li>
							<li>citation manipulation</li>
							<li>recommending citations primarily to increase an individual's, journal's, or institution's citation metrics</li>
						</ul>
						<p>Citations should be included because they are scientifically relevant to the work.</p>
					</section>

					<section id="editorial-independence" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Editorial independence</h2>
						<p>ASFIRJ is committed to editorial independence.</p>
						<p>Editorial decisions shall not be improperly influenced by:</p>
						<ul>
							<li>commercial interests</li>
							<li>advertising</li>
							<li>sponsorship</li>
							<li>institutional affiliations</li>
							<li>political considerations</li>
							<li>personal relationships</li>
							<li>financial interests</li>
							<li>other external pressures</li>
						</ul>
						<p>The scientific merit and quality of the manuscript shall remain central to editorial decision-making.</p>
					</section>

					<section id="complaints" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Complaints and appeals</h2>
						<p>ASFIRJ welcomes legitimate concerns regarding its editorial or publication processes. Authors may appeal an editorial decision when they believe that the decision resulted from a significant misunderstanding, procedural error, or demonstrable failure to appropriately consider the scientific content of the manuscript. Appeals should provide a clear and evidence-based explanation of the grounds for appeal. ASFIRJ will consider complaints and appeals fairly and, where appropriate, may involve an independent editor or other appropriate person in their assessment.</p>
						<p>Complaints concerning editorial conduct, publication ethics, or other aspects of the publication process should be directed to the Editor-in-Chief or ASFIRJ Editorial Office at:</p>
						<div class="bg-gray-50 rounded-lg p-4 flex items-center gap-3 mt-3">
							<div class="w-9 h-9 rounded-full bg-[#80078b] flex items-center justify-center text-white"><i class="fas fa-envelope"></i></div>
							<div>
								<div class="text-xs text-gray-500 uppercase tracking-wide">Email</div>
								<a href="mailto:asfirj@asfirj.org" class="text-[#80078b] font-semibold hover:underline">asfirj@asfirj.org</a>
							</div>
						</div>
						<p class="mt-3">The journal will make reasonable efforts to acknowledge and investigate legitimate complaints promptly and confidentially.</p>
					</section>

					<section id="allegations" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Allegations of publication misconduct</h2>
						<p>ASFIRJ takes allegations of publication and research misconduct seriously, whether they arise before or after publication.</p>
						<p>Allegations may concern, among other matters:</p>
						<ul>
							<li>plagiarism</li>
							<li>fabrication or falsification</li>
							<li>duplicate publication</li>
							<li>inappropriate authorship</li>
							<li>undisclosed conflicts of interest</li>
							<li>unethical research practices</li>
							<li>manipulation of peer review</li>
							<li>citation manipulation</li>
							<li>image manipulation</li>
							<li>data manipulation</li>
							<li>inappropriate use of AI</li>
							<li>other forms of publication malpractice</li>
						</ul>
						<p>When an allegation is received, ASFIRJ will assess the available information and determine whether further investigation is warranted.</p>
						<p>Depending on the nature and seriousness of the concern, the journal may:</p>
						<ul>
							<li>request an explanation from the authors</li>
							<li>request supporting documentation or original data</li>
							<li>consult editors, reviewers, or independent experts</li>
							<li>contact the relevant institution, employer, ethics committee, or funder</li>
							<li>issue a correction or other post-publication notice</li>
							<li>issue an expression of concern</li>
							<li>retract the article</li>
							<li>take other appropriate action to protect the integrity of the scholarly record</li>
						</ul>
						<p>The journal will seek to ensure that investigations are conducted fairly, confidentially, and without prejudging the outcome.</p>
					</section>

					<section id="corrections" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Corrections, retractions and expressions of concern</h2>
						<p>ASFIRJ recognizes its responsibility to correct the scholarly record when errors or misconduct are identified after publication.</p>
						<p>Depending on the circumstances, ASFIRJ may publish:</p>
						<div class="space-y-4 mt-4">
							<div class="border border-gray-200 rounded-lg p-4">
								<h3 class="font-bold text-[#250242] mb-1">Correction</h3>
								<p class="m-0 text-sm">A correction may be issued when a published article contains an error that affects the accuracy or clarity of the publication but does not invalidate the overall findings.</p>
							</div>
							<div class="border border-gray-200 rounded-lg p-4">
								<h3 class="font-bold text-[#250242] mb-1">Retraction</h3>
								<p class="m-0 text-sm">A published article may be retracted when there is compelling evidence that the findings are unreliable, the article contains serious research or publication misconduct, or the publication violates fundamental ethical or editorial requirements.</p>
							</div>
							<div class="border border-gray-200 rounded-lg p-4">
								<h3 class="font-bold text-[#250242] mb-1">Expression of concern</h3>
								<p class="m-0 text-sm">An expression of concern may be issued when substantial concerns have been raised about a published article but an investigation is ongoing or the available evidence is not yet sufficient to reach a final conclusion. Corrections, retractions, and expressions of concern will be clearly linked to the original article and maintained as part of the scholarly record.</p>
							</div>
						</div>
					</section>

					<section id="post-publication" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Post-publication concerns</h2>
						<p>ASFIRJ encourages readers and members of the scientific community to report credible concerns about published articles. Concerns should be submitted to the ASFIRJ Editorial Office with sufficient information to allow the matter to be assessed. The journal will review credible concerns and, where necessary, initiate an investigation and take appropriate corrective action.</p>
					</section>

					<section id="whistleblowers" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Protection of whistleblowers and complainants</h2>
						<p>ASFIRJ will make reasonable efforts to protect the confidentiality of individuals who raise legitimate concerns about research or publication misconduct. The journal will not tolerate retaliation against individuals who, in good faith, report legitimate concerns. However, knowingly false, malicious, or defamatory allegations may themselves constitute misconduct and may be handled appropriately.</p>
					</section>

					<section id="confidentiality" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Editorial and peer-review confidentiality</h2>
						<p>All manuscripts and associated editorial and peer-review communications will be treated as confidential unless the journal's stated peer-review model provides otherwise.</p>
						<p>Editors and reviewers must not:</p>
						<ul>
							<li>disclose unpublished manuscript content</li>
							<li>share manuscripts without authorization</li>
							<li>use unpublished information for personal or professional advantage</li>
							<li>disclose the identity of reviewers where the journal's review model requires reviewer anonymity</li>
						</ul>
					</section>

					<section id="peer-review-malpractice" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Malpractice involving the peer-review process</h2>
						<p>ASFIRJ considers manipulation of peer review to be a serious form of publication malpractice.</p>
						<p>Examples include:</p>
						<ul>
							<li>submitting fabricated reviewer identities or contact information</li>
							<li>attempting to influence reviewers improperly</li>
							<li>impersonating a reviewer</li>
							<li>submitting fraudulent peer-review reports</li>
							<li>coordinating fraudulent review activities</li>
							<li>manipulating reviewer recommendations</li>
							<li>otherwise attempting to circumvent the journal's independent peer-review process</li>
						</ul>
						<p>Where peer-review manipulation is suspected, ASFIRJ may suspend the editorial process, reject the manuscript, investigate previously published articles, and take other appropriate action.</p>
					</section>

					<section id="editorial-misconduct" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Editorial misconduct</h2>
						<p>Editors and members of the editorial team are also subject to the journal's publication ethics standards.</p>
						<p>Editorial misconduct may include:</p>
						<ul>
							<li>inappropriate interference with peer review</li>
							<li>discrimination or bias</li>
							<li>misuse of confidential information</li>
							<li>undisclosed conflicts of interest</li>
							<li>coercive citation</li>
							<li>inappropriate preferential treatment of manuscripts</li>
							<li>manipulation of editorial decisions</li>
							<li>misuse of unpublished research</li>
							<li>other behaviour that compromises the integrity or independence of the journal</li>
						</ul>
						<p>Concerns about editorial misconduct may be submitted to the Editor-in-Chief or, where the complaint concerns the Editor-in-Chief, to an appropriate senior representative of the publisher - ASFI.</p>
					</section>

					<section id="research-integrity" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Research integrity beyond publication</h2>
						<p>ASFIRJ recognizes that publication ethics are closely connected to broader research integrity. The journal expects authors to comply with applicable standards concerning responsible research conduct, including appropriate research design, ethical treatment of participants and animals, responsible data management, transparency, and honest reporting. Where evidence suggests that a published article resulted from serious research misconduct, ASFIRJ may contact the relevant institution or authority and take appropriate action regarding the publication.</p>
					</section>

					<section id="continuous-improvement" class="scroll-mt-28">
						<h2 class="text-xl md:text-2xl font-bold mb-3">Commitment to continuous improvement</h2>
						<p>ASFIRJ is committed to continually strengthening its editorial and publishing practices. The journal will periodically review this Publication Ethics and Publication Malpractice Statement and update it as necessary to reflect developments in international standards, scholarly publishing practices, research integrity, and emerging technologies. ASFIRJ is committed to fostering a publishing environment that is ethical, transparent, inclusive, rigorous, fair, and internationally competitive, while contributing to the advancement and global visibility of high-quality research from Africa and beyond.</p>
