							<a href="mailto:asfirj@asfirj.org" class="bg-white text-[#250242] px-5 py-2 rounded-full text-sm font-semibold hover:bg-gray-100 transition whitespace-nowrap">asfirj@asfirj.org</a>
						</div>
					</section>

